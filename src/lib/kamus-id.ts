export const KAMUS = { ...KAMUS_RUST, ...KAMUS_UI, ...KAMUS_LAMA };
export const POLA = [...POLA_UI, ...POLA_RUST, ...POLA_LAMA];

const PETA = new Map(Object.entries(KAMUS).map(([k, v]) => [k.replace(/\s+/g, " ").trim(), v]));

function satu(kunci) {
  const t = PETA.get(kunci);
  if (t != null) return t;
  for (const [re, ganti] of POLA) {
    const m = re.exec(kunci);
    if (!m) continue;
    const r = typeof ganti === "function" ? ganti(...m.slice(1)) : kunci.replace(re, ganti);
    if (r != null) return r;
  }
  return null;
}

const BATAS_KALIMAT = /(?<=[.!?)])\s+(?=[A-Z(])/;

export function cari(teks) {
  const kunci = teks.replace(/\s+/g, " ").trim();
  const t = satu(kunci);
  if (t != null) return t;
  const bagian = kunci.split(BATAS_KALIMAT);
  if (bagian.length < 2) return null;
  const hasil = [];
  for (const b of bagian) {
    const x = satu(b);
    if (x == null) return null;
    hasil.push(x);
  }
  return hasil.join(" ");
}

pasangPenerjemah((teks) => cari(teks) ?? teks);
pasangDalamRust((teks) => cari(teks) ?? teks);
